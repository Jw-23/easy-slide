"""Rebuild the portable PNG used by the feature-tour project (optional dev helper)."""
from pathlib import Path
import base64
import io
import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt
import numpy as np

x = np.linspace(-3, 3, 300)
fig, ax = plt.subplots(figsize=(10, 5.5), dpi=150)
fig.patch.set_facecolor('#f8fbfa')
ax.set_facecolor('#f8fbfa')
ax.plot(x, x*x / 2, color='#23796e', lw=2.4, label=r'$f(x)=x^2/2$')
points = np.array([2.75, 1.8, 1.15, .68, .32, .08])
ax.scatter(points, points*points/2, c=np.arange(len(points)), cmap='viridis', s=60, zorder=3, edgecolors='white', linewidths=1.5)
for left, right in zip(points[:-1], points[1:]):
    ax.annotate('', xy=(right, right*right/2), xytext=(left, left*left/2), arrowprops={'arrowstyle':'->', 'color':'#78988d', 'lw':1.3, 'connectionstyle':'arc3,rad=-.18'})
ax.set_xlabel('x', color='#6a8277')
ax.set_ylabel('Objective value', color='#6a8277')
ax.spines[['top','right']].set_visible(False)
for name in ['left','bottom']: ax.spines[name].set_color('#cddbd4')
ax.tick_params(colors='#83988d')
ax.grid(alpha=.16, color='#99b6a7')
ax.legend(frameon=False, loc='upper left', labelcolor='#456759')
fig.tight_layout(pad=2)
stream=io.BytesIO()
fig.savefig(stream, format='png', facecolor=fig.get_facecolor())
plt.close(fig)
encoded=base64.b64encode(stream.getvalue()).decode()
path=Path(__file__).resolve().parents[1]/'src'/'example-assets.ts'
path.write_text('// Generated by scripts/generate-example-chart.py; embedded for offline project portability.\nexport const exampleAssets:Record<string,string>={\n  "assets/convergence.png":"data:image/png;base64,'+encoded+'"\n};\n')
